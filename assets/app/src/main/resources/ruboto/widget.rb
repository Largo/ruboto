module Ruboto
  module Widget
    # Defines a widget method like RubotoActivity#linear_layout(params = {}, &block).
    # A closure instead of a class_eval'ed source string saves parsing and
    # building the method once per widget and owner class.  In a fragment the
    # view's context is the fragment's activity.
    def self.define_widget_method(owner, method_name, widget_class, fragment = false)
      owner.send(:define_method, method_name) do |params = {}, &block|
        context = fragment ? activity : self
        if (force_style = params.delete(:default_style))
          rv = widget_class.new(context, nil, force_style)
        elsif (api_key = params.delete(:apiKey))
          rv = widget_class.new(context, api_key)
        else
          rv = widget_class.new(context)
        end

        if (parent = (params.delete(:parent) || @view_parent))
          parent.addView(rv, (params.delete(:parent_index) || parent.child_count))
        end

        rv.configure context, params

        return rv unless block

        old_view_parent, @view_parent = @view_parent, rv
        block.call
        @view_parent = old_view_parent

        rv
      end
    end

    # Widget methods waiting for the android.app.Fragment proxy: method name => widget class
    PENDING_FRAGMENT_WIDGETS = {}

    # android.app.Fragment gets the widget methods as well, but building its
    # proxy costs about 100 M instructions under -Xint (a big class, and its
    # Java superclasses and interfaces) and most apps never use platform
    # fragments.  So the methods are added once the proxy exists: right away
    # if it already does, else when Ruby subclasses a Java class (a Fragment
    # subclass needs the Fragment proxy), or at the first call of a widget
    # method on a fragment that is only known to Ruby as a Java object.
    def self.define_fragment_widget_method(method_name, widget_class)
      PENDING_FRAGMENT_WIDGETS[method_name.to_sym] = widget_class
      define_fragment_widget_methods if fragment_proxy_created?
    end

    # Proxy classes are registered in their package module when they are built.
    def self.fragment_proxy_created?
      Java::AndroidApp.const_defined?(:Fragment, false)
    end

    def self.define_fragment_widget_methods
      until PENDING_FRAGMENT_WIDGETS.empty?
        method_name, widget_class = PENDING_FRAGMENT_WIDGETS.shift
        define_widget_method(Java::AndroidApp::Fragment, method_name, widget_class, true)
      end
    end

    # Prepended to the singleton class of java.lang.Object: JRuby defines its
    # own "inherited" there, which must still run.
    module FragmentInheritedHook
      def inherited(subclass)
        unless PENDING_FRAGMENT_WIDGETS.empty?
          Ruboto::Widget.define_fragment_widget_methods if Ruboto::Widget.fragment_proxy_created?
        end
        super
      end
    end
    Java::JavaLang::Object.singleton_class.prepend FragmentInheritedHook

    # Included into java.lang.Object, for fragments created by Java code.
    # There is deliberately no respond_to_missing?: it would run on every
    # failed respond_to? of every Java object, and set_attribute makes many
    # (7x slower misses under -Xint).  So until the methods are defined,
    # such a fragment does not report them through respond_to?,
    # method_defined? or instance_methods.
    module FragmentMethodMissing
      def method_missing(method, *args, &block)
        if Ruboto::Widget.pending_fragment_method?(self, method)
          Ruboto::Widget.define_fragment_widget_methods
          return __send__(method, *args, &block)
        end
        super
      end
    end
    Java::JavaLang::Object.send(:include, FragmentMethodMissing)

    def self.pending_fragment_method?(object, method)
      PENDING_FRAGMENT_WIDGETS.include?(method.to_sym) && fragment_proxy_created? &&
          object.is_a?(Java::AndroidApp::Fragment)
    end
  end
end

module Ruboto
  module WidgetFunctions
    private

    def ruboto_import_widgets(*widgets)
      widgets.each { |i| ruboto_import_widget i }
    end

    def ruboto_import_widget(class_name, package_name='android.widget')
      if class_name.is_a?(String) or class_name.is_a?(Symbol)
        klass = java_import("#{package_name}.#{class_name}") || eval("Java::#{package_name}.#{class_name}")
      else
        klass = class_name
        java_import klass
        class_name = klass.java_class.name.split('.')[-1]
      end

      return unless klass

      widget_class = klass.is_a?(Array) ? klass.first : klass # java_import returns the list of imported classes
      method_name = class_name.to_s.gsub(/([A-Z])/) { '_' + $1.downcase }[1..-1]
      Ruboto::Widget.define_widget_method(RubotoActivity, method_name, widget_class)
      Ruboto::Widget.define_fragment_widget_method(method_name, widget_class)

      setup_list_view if class_name == :ListView
      setup_spinner if class_name == :Spinner
      setup_button if class_name == :Button
      setup_image_button if class_name == :ImageButton
      setup_linear_layout if class_name == :LinearLayout
      setup_relative_layout if class_name == :RelativeLayout

      klass
    end

    #
    # Special widget setup
    #

    def setup_linear_layout
      Java::android.widget.LinearLayout.setup_constant_conversion
    end

    def setup_relative_layout
      Java::android.widget.RelativeLayout.setup_constant_conversion
    end

    def setup_button
      # legacy
    end

    def setup_image_button
      # legacy
    end

    def setup_list_view
      android.widget.ListView.__persistent__ = true
      android.widget.ListView.class_eval do
        def configure(context, params = {})
          if (list = params.delete(:list))
            item_layout = params.delete(:item_layout) || android.R::layout::simple_list_item_1
            params[:adapter] = android.widget.ArrayAdapter.new(context, item_layout, list)
          end
          super(context, params)
        end

        def reload_list(list)
          # Copy first: if the caller passes the adapter's own backing list
          # (a Ruby Array is a java.util.List), clear would empty it.
          items = list.to_a.dup
          adapter.clear
          adapter.addAll(items)
          adapter.notifyDataSetChanged
          invalidate
        end
      end
    end

    def setup_spinner
      android.widget.Spinner.__persistent__ = true
      android.widget.Spinner.class_eval do
        def configure(context, params = {})
          if (list = params.delete(:list))
            item_layout = params.delete(:item_layout)
            params[:adapter] = android.widget.ArrayAdapter.new(context, item_layout || android.R::layout::simple_spinner_item, list)
            dropdown_layout = params.delete(:dropdown_layout)
            params[:adapter].setDropDownViewResource(dropdown_layout) if dropdown_layout
          end
          super(context, params)
        end

        def reload_list(list)
          # Copy first: if the caller passes the adapter's own backing list
          # (a Ruby Array is a java.util.List), clear would empty it.
          items = list.to_a.dup
          adapter.clear
          adapter.addAll(items)
          adapter.notifyDataSetChanged
          invalidate
        end
      end
    end
  end
end
Object.send(:include, Ruboto::WidgetFunctions)
